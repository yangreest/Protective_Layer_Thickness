package com.example.gtj_sd_dg240.model;

public class CPointBean {
    public float x;
    public float y;

    public CPointBean() {
    }

    public CPointBean(float x, float y) {
        this.x = x;
        this.y = y;
    }

    public void setCoordinatePoints(float x, float y) {
        this.x = x;
        this.y = y;
    }
}
